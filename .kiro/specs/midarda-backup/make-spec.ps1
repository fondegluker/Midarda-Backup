# Требования к проекту Midarda-Backup

## 1. Обзор

### 1.1. Назначение
Midarda-Backup — система умного резервного копирования файлов бэкапов MSSQL
из локальной папки на удалённые ресурсы (SMB-шара и/или FTP/FTPS),
с контролем целостности, ротацией копий, мониторингом состояния и
уведомлениями.

Проект состоит из двух исполняемых файлов:
- **Установщик** (installer.exe) — консольное приложение с цветным выводом.
- **Служба** (midarda-backup.exe) — Windows-служба, работающая от имени
  пользователя midarda-backup.

### 1.2. Глоссарий
| Термин | Значение |
|--------|----------|
| Мониторинг | Отслеживание появления новых файлов в папке-источнике |
| Транзакция | Полный цикл обработки одного файла (проверка - копирование - ротация) |
| Стабилизация | Ожидание завершения записи файла (закрытие дескриптора + пауза) |
| Ротация | Удаление устаревших копий сверх лимита из конфига |
| Watchdog | Механизм само-мониторинга службы через heartbeat |
| EFS | Encrypting File System — шифрование файлов средствами Windows |

